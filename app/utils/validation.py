"""
Validation utilities for the PO Translation System.

Validates Excel files, extensions, and content.
"""

import io
import re
import uuid
from typing import Any

from openpyxl import load_workbook


def validate_excel_file(content: bytes) -> bool:
    """
    Validate that the uploaded content is a valid Excel file.

    Args:
        content: Raw bytes of the uploaded file

    Returns:
        bool: True if valid Excel file, False otherwise
    """
    try:
        workbook = load_workbook(io.BytesIO(content), data_only=True)
        try:
            # Check that at least one sheet has data
            for sheet in workbook.worksheets:
                for row in sheet.iter_rows(values_only=True):
                    if any(value is not None for value in row):
                        return True
            return False
        finally:
            workbook.close()
    except Exception:
        return False


def is_valid_file_id(file_id: str) -> bool:
    """
    Check that a file ID is a UUID generated by the upload endpoint.

    File IDs are used to build glob patterns on disk, so anything that is
    not a plain UUID must be rejected.

    Args:
        file_id: File ID received from the client

    Returns:
        bool: True if the ID is a canonical UUID string
    """
    try:
        return str(uuid.UUID(file_id)) == file_id.lower()
    except (ValueError, AttributeError, TypeError):
        return False


def validate_cell_value(value: Any) -> bool:
    """
    Check if a cell value should be treated as translatable text.

    Args:
        value: Cell value to validate

    Returns:
        bool: True if value appears to be translatable text
    """
    if value is None:
        return False

    value_str = str(value).strip()

    if not value_str:
        return False

    # Skip pure numbers
    try:
        float(value_str)
        return False
    except ValueError:
        pass

    # Skip PO identifiers
    if value_str.upper().startswith(("PO-", "PO/")):
        return False

    # Skip material codes
    if re.match(r'^(MAT|ABC|HYD)-\d+$', value_str, re.IGNORECASE):
        return False

    # Skip part numbers
    if re.match(r'^(PART|JCB)-\d+$', value_str, re.IGNORECASE):
        return False

    # Skip employee IDs
    if re.match(r'^EMP\d+$', value_str, re.IGNORECASE):
        return False

    # Skip vendor IDs
    if re.match(r'^V\d+$', value_str, re.IGNORECASE):
        return False

    # Skip dates
    if re.match(r'^\d{2}/\d{2}/\d{4}$', value_str) or re.match(r'^\d{4}-\d{2}-\d{2}$', value_str):
        return False

    # Skip URLs
    if value_str.startswith(("http://", "https://", "www.")):
        return False

    # Skip email addresses
    if "@" in value_str and value_str.count("@") == 1:
        parts = value_str.split("@")
        if parts[0] and parts[1] and "." in parts[1]:
            return False

    # Skip pure numeric values
    if value_str.isdigit():
        return False

    # If we get here, it's likely translatable text
    return True


def validate_identifier(value: str) -> bool:
    """
    Check if a value is a PO identifier that should not be translated.

    Args:
        value: String value to check

    Returns:
        bool: True if value is a protected identifier
    """
    patterns = [
        r'^PO-\d+$',          # PO-10025
        r'^PO/\d+/\d+$',      # PO/2026/001
        r'^MAT-\d+$',         # MAT-1025
        r'^[A-Z0-9]+-\d+$',   # Generic part numbers
        r'^EMP\d+$',          # EMP001, EMP102
        r'^V\d+$',            # V001, V002
        r'^\d+$',             # Pure numbers
    ]

    for pattern in patterns:
        if re.match(pattern, value, re.IGNORECASE):
            return True

    return False
